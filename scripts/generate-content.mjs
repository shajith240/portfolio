// scripts/generate-content.mjs
//
// Content auto-discovery: scans the content folders under public/
// and emits data/generated/content.ts. Runs automatically before
// `npm run dev` and `npm run build` (predev/prebuild), so adding a
// wallpaper or motivation image and committing is ALL that's ever
// needed — no code changes, the site adapts.
//
//   public/wallpapers/         → GENERATED_WALLPAPERS (desktop + phone)
//   public/motivation_quotes/  → GENERATED_MOTIVATION_IMAGES

import { readdirSync, mkdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname, extname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const IMAGE_EXTS = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif", ".gif"]);

function listDir(rel) {
  const abs = join(root, "public", rel);
  if (!existsSync(abs)) return [];
  return readdirSync(abs, { withFileTypes: true })
    .filter((e) => e.isFile())
    .map((e) => e.name)
    .sort();
}

const wallpapers = listDir("wallpapers").filter((f) => IMAGE_EXTS.has(extname(f).toLowerCase()));
const motivationImages = listDir("motivation_quotes")
  .filter((f) => IMAGE_EXTS.has(extname(f).toLowerCase()))
  .map((f) => `/motivation_quotes/${f}`);

const banner = `// AUTO-GENERATED by scripts/generate-content.mjs — do not edit.
// Regenerated on every \`npm run dev\` / \`npm run build\`. To change
// what's here, add/remove files in public/wallpapers or
// public/motivation_quotes and restart/redeploy.`;

const out = `${banner}

export const GENERATED_WALLPAPERS: string[] = ${JSON.stringify(wallpapers, null, 2)};

export const GENERATED_MOTIVATION_IMAGES: string[] = ${JSON.stringify(motivationImages, null, 2)};
`;

mkdirSync(join(root, "data", "generated"), { recursive: true });
writeFileSync(join(root, "data", "generated", "content.ts"), out);

console.log(
  `[content] ${wallpapers.length} wallpaper(s), ${motivationImages.length} motivation image(s) → data/generated/content.ts`
);
